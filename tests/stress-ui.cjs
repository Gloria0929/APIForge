    await dialog.getByRole('tab', { name: '历史记录', exact: true }).click();
    await dialog.locator('.el-table__row').filter({ hasText: '常规负载 · 基准' }).locator('.el-checkbox').click();
    await dialog.locator('.el-table__row').filter({ hasText: '常规负载 · 第二次' }).locator('.el-checkbox').click();
